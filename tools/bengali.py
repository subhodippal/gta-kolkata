def phonetic(w):
    w = w.lower()
    out = []
    i = 0
    prev_cons = False
    while i < len(w):
        ch = w[i]
        if not ch.isalpha():
            out.append(ch); prev_cons = False; i += 1; continue
        # silent final e
        if ch == "e" and i == len(w) - 1 and len(w) > 3 and prev_cons:
            i += 1; continue
        # English -er / -ers ending sounds like "ar"
        if prev_cons and w[i:] in ("er", "ers"):
            out.append("া"); prev_cons = False; i += 1; continue
        # word-initial y + vowel -> ইয়
        if ch == "y" and i == 0 and len(w) > 1 and w[1] in "aeiou":
            out.append("ইয়"); prev_cons = True; i += 1; continue
        if w.startswith("qu", i):
            out.append(("্" if prev_cons else "") + "কু"); prev_cons = False; i += 2; continue
        # vowel?
        m = None
        for v, ind, sign in VOW:
            if w.startswith(v, i) and not (v == "y" and not prev_cons):
                m = (v, ind, sign); break
        if m and (m[0] != "y" or prev_cons):
            out.append(m[2] if prev_cons else m[1])
            prev_cons = False; i += len(m[0]); continue
        # consonant
        for c, b in CONS:
            if w.startswith(c, i):
                if c == "c" and i + 1 < len(w) and w[i + 1] in "eiy":
                    b = "স"
                if prev_cons and out and b not in ("ং",):
                    if out[-1] == b and c in ("t", "d", "l", "n", "m", "p", "s", "k", "b", "g"):
                        pass  # double letter -> conjunct of same
                    out.append("্")
                out.append(b)
                prev_cons = b not in ("ং",)
                if b == "ওয়" and out[-2:-1] == ["্"]:
                    out[-2:] = ["ওয়"]
                i += len(c)
                break
        else:
            i += 1
    s = "".join(out)
    s = s.replace("্্", "্")
    return s


def word_bn(tok, is_last):
    lw = tok.lower()
    if lw.rstrip(".") == "st" and not is_last:
        return "সেন্ট"
    if lw in WORDS:
        return WORDS[lw]
    if lw.rstrip(".") in WORDS:
        return WORDS[lw.rstrip(".")]
    if lw.endswith("'s") and lw[:-2] in WORDS:
        return WORDS[lw[:-2]] + "স"
    if tok.isupper() and 1 <= len(tok) <= 5 and tok.isalpha():
        return "".join(LETTERS.get(c, c) for c in tok)
    if re.fullmatch(r"[A-Z](\.[A-Z])+\.?", tok):
        return ".".join(LETTERS.get(c, c) for c in tok.replace(".", "")) + "."
    if re.fullmatch(r"\d+(st|nd|rd|th)?", lw):
        return re.sub(r"(st|nd|rd|th)$", "", lw).translate(BN_DIGITS)
    if any(c.isalpha() for c in tok):
        return phonetic(tok.replace("'", ""))
    return tok.translate(BN_DIGITS)


