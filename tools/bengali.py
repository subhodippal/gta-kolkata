def to_bengali(name):
    if not name:
        return name
    if re.search("[ঀ-৿]", name):
        return name
    if name in FULL:
        return FULL[name]
    m = re.match(r"(?i)^statue of (.+)$", name)
    if m:
        return to_bengali(m.group(1)) + "-এর মূর্তি"
    low = name.lower()
    for en, bn in PHRASES:
        k = low.find(en)
        if k >= 0 and (k == 0 or not low[k - 1].isalpha()) and (k + len(en) == len(low) or not low[k + len(en)].isalpha()):
            left, right = name[:k].strip(), name[k + len(en):].strip()
            return " ".join(x for x in [to_bengali(left) if left else "", bn, to_bengali(right) if right else ""] if x)
    toks = re.findall(r"[A-Za-z0-9][A-Za-z0-9'\.]*|&|[^\sA-Za-z0-9]", name)
    words = [t for t in toks]
    out = []
    for i, t in enumerate(words):
        b = word_bn(t, i == len(words) - 1)
        if b:
            out.append(b)
    s = " ".join(out)
    s = re.sub(r"\s+([,\)\-:])", r"\1", s).replace("( ", "(")
    return s.strip()


